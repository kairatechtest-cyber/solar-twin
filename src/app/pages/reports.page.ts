import { Component, computed, signal } from '@angular/core';
import { IconComponent } from '../shared/icon.component';
import { ChartComponent, axisStyle } from '../shared/chart.component';
import { KpiComponent, PageHeadComponent } from '../shared/bits';
import { FmtPipe } from '../shared/pipes';
import { apiResource } from '../core/resource';
import { downloadCsv } from '../core/util';

interface Row { label: string; energyKwh: number; peakKw: number; insolationKwhM2: number; prPct: number; cufPct: number; specificYield: number; availPct: number; co2Tons: number }

@Component({
  selector: 'app-reports',
  standalone: true,
  imports: [IconComponent, ChartComponent, KpiComponent, PageHeadComponent, FmtPipe],
  template: `
    <div class="page">
      <app-page-head title="Reports & KPIs" sub="Energy, performance ratio, CUF, specific yield and availability">
        <div class="tabs no-print"><button class="tab" [class.on]="period() === 'daily'" (click)="period.set('daily')">Daily (30 d)</button><button class="tab" [class.on]="period() === 'monthly'" (click)="period.set('monthly')">Monthly (12 m)</button></div>
        <button class="btn ghost sm no-print" (click)="exportCsv()"><app-icon name="download" [size]="14" /> CSV</button>
        <button class="btn ghost sm no-print" (click)="print()"><app-icon name="printer" [size]="14" /> Print / PDF</button>
      </app-page-head>
      <p class="print-only">SolarTwin — {{ period() }} KPI report · {{ res.data()?.capacityKwp }} kWp / {{ res.data()?.capacityAcKw }} kW AC · DEMO DATA</p>

      <div class="grid g4">
        <app-kpi icon="zap" label="Total energy" [value]="(sum('energyKwh') / 1000) | fmt:1" unit="MWh" />
        <app-kpi icon="gauge" label="Avg. performance ratio" [value]="avg('prPct') | fmt:1" unit="%" color="#22c55e" [sub]="'CUF ' + (avg('cufPct') | fmt:1) + ' %'" />
        <app-kpi icon="sun" label="Specific yield" [value]="sum('specificYield') | fmt:0" unit="kWh/kWp" color="#f59e0b" [sub]="'Avg availability ' + (avg('availPct') | fmt:1) + ' %'" />
        <app-kpi icon="leaf" label="CO₂ avoided (estimate)" [value]="sum('co2Tons') | fmt:1" unit="t" color="#22c55e" />
      </div>
      <div class="card mt"><h2>Energy and performance ratio</h2><app-chart [option]="chart()" [height]="300" /></div>
      <div class="card tbl-wrap mt"><table>
        <thead><tr><th>Period</th><th>Energy (kWh)</th><th>Peak (kW)</th><th>Insolation (kWh/m²)</th><th>PR (%)</th><th>CUF (%)</th><th>Yield (kWh/kWp)</th><th>Availability (%)</th><th>CO₂ (t)</th></tr></thead>
        <tbody>@for (r of reversed(); track r.label) {
          <tr><td>{{ r.label }}</td><td>{{ r.energyKwh | fmt:0 }}</td><td>{{ r.peakKw | fmt:0 }}</td><td>{{ r.insolationKwhM2 | fmt:2 }}</td><td>{{ r.prPct | fmt:1 }}</td><td>{{ r.cufPct | fmt:1 }}</td>
            <td>{{ r.specificYield | fmt:2 }}</td><td>{{ r.availPct | fmt:1 }}</td><td>{{ r.co2Tons | fmt:2 }}</td></tr>
        }</tbody>
      </table></div>
      <p class="muted">PR = energy ÷ (kWp × insolation). CUF = energy ÷ (AC capacity × hours). History is synthetic DEMO data generated by the simulator.</p>
    </div>`,
})
export class ReportsPage {
  period = signal<'daily' | 'monthly'>('daily');
  res = apiResource<{ rows: Row[]; capacityKwp: number; capacityAcKw: number }>(() => `/analytics/report?period=${this.period()}`);
  rows = computed(() => this.res.data()?.rows ?? []);
  reversed = computed(() => [...this.rows()].reverse());
  private days = computed(() => this.rows().filter((r) => r.insolationKwhM2 > 0.5));
  sum = (k: keyof Row) => this.rows().reduce((a, r) => a + (r[k] as number), 0);
  avg = (k: keyof Row) => (this.days().length ? this.days().reduce((a, r) => a + (r[k] as number), 0) / this.days().length : 0);
  chart = computed(() => {
    const rows = this.rows();
    return {
      grid: { left: 56, right: 50, top: 30, bottom: 36 }, tooltip: { trigger: 'axis' }, legend: { textStyle: { color: '#8ea0c9' }, top: 0, left: 'center' },
      xAxis: { type: 'category', data: rows.map((r) => r.label), ...axisStyle },
      yAxis: [{ type: 'value', name: 'kWh', nameTextStyle: { color: '#8ea0c9' }, ...axisStyle }, { type: 'value', name: 'PR %', min: 0, max: 100, nameTextStyle: { color: '#8ea0c9' }, ...axisStyle, splitLine: { show: false } }],
      series: [{ name: 'Energy', type: 'bar', itemStyle: { color: '#3b82f6' }, data: rows.map((r) => +r.energyKwh.toFixed(0)) },
        { name: 'PR', type: 'line', yAxisIndex: 1, showSymbol: false, lineStyle: { color: '#22c55e' }, data: rows.map((r) => +r.prPct.toFixed(1)) }],
    };
  });
  exportCsv() {
    downloadCsv(`kpi_${this.period()}.csv`, [['period', 'energy_kWh', 'peak_kW', 'insolation_kWh_m2', 'PR_%', 'CUF_%', 'specific_yield_kWh_kWp', 'availability_%', 'CO2_t'],
      ...this.rows().map((r) => [r.label, r.energyKwh.toFixed(0), r.peakKw.toFixed(1), r.insolationKwhM2.toFixed(2), r.prPct.toFixed(1), r.cufPct.toFixed(1), r.specificYield.toFixed(2), r.availPct.toFixed(1), r.co2Tons.toFixed(2)])]);
  }
  print() { window.print(); }
}
